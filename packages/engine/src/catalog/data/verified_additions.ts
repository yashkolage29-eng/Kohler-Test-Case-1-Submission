import type { Anchor, DimMm, FixtureClass, SKU } from "../schema.js";
import { CATEGORY_BY_CLASS } from "../schema.js";

const checkedOn = "2026-09-17";

function product(
  model_id: string,
  name: string,
  fixture_class: FixtureClass,
  dim: DimMm,
  price: number,
  url: string,
  dimensionNote: string,
  anchor: Anchor,
  part: string,
  feature_tags: SKU["feature_tags"],
  water?: SKU["water"],
  extraNote = "",
  finish?: string,
): SKU {
  const source = (note: string) => [{ url, checkedOn, note }];
  return {
    model_id, name, fixture_class,
    category: CATEGORY_BY_CLASS[fixture_class],
    dim, price,
    finish_options: [finish ?? (["faucet", "shower", "accessory"].includes(fixture_class) ? "chrome" : "white")],
    geometry_descriptor: {
      anchor,
      primitives: [{ part, kind: { shape: "box", sizeMm: { ...dim } }, offsetMm: { x: 0, y: 0, z: 0 }, finishable: true }],
    },
    feature_tags, water,
    compatibility: [],
    substitutionIds: [],
    evidence: {
      identity: { status: "verified", value: { model_id, name, fixture_class }, sources: source("Official India PDP title, SKU and product description; exact suffix retained.") },
      dimensions: { status: "verified", value: { ...dim }, sources: source(dimensionNote) },
      price: { status: "verified", value: { base: price }, sources: source("India PDP MRP/list price in INR, inclusive of taxes; not the discounted selling price. Snapshot, not a live quote.") },
      planningNote: `Geometry is an authored bounding-box proxy, not manufacturer shape. Compatibility is planning-level; installation and required supporting components require trade verification. ${extraNote}`.trim(),
    },
  };
}

